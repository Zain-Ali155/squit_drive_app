import test from "node:test";
import assert from "node:assert/strict";
import { renderToStaticMarkup } from "react-dom/server";
import { DriveWorkspace } from "../components/drive-workspace";

test("Drive page renders the responsive cloud-drive navigation and existing core actions", () => {
  const markup = renderToStaticMarkup(<DriveWorkspace apiBaseUrl="http://127.0.0.1:4000" authControls={<div>Sign out</div>} />);
  const sidebarMarkup = markup.match(/<aside[^>]*aria-label="Drive sidebar"[\s\S]*?<\/aside>/u)?.[0] ?? "";
  assert.match(markup, /SQUID Drive/u);
  assert.doesNotMatch(markup, /Local demo/u);
  assert.match(markup, /aria-label="Drive navigation"/u);
  assert.match(markup, /My Drive/u);
  assert.match(markup, /Favorites/u);
  assert.match(markup, /Recent/u);
  assert.match(markup, /Trash/u);
  assert.match(markup, /aria-label="Storage usage"/u);
  assert.match(markup, /<header[\s\S]*?<div class="flex items-center justify-between gap-3 lg:contents">[\s\S]*?New[\s\S]*?Sign out[\s\S]*?<\/div><label[\s\S]*?Search all Drive[\s\S]*?<\/header>/u);
  assert.match(markup, /<nav aria-label="Drive views"[^>]*class="flex gap-1 overflow-x-auto[^>]*>[\s\S]*?My Drive[\s\S]*?Favorites[\s\S]*?Recent[\s\S]*?<\/nav>/u);
  assert.doesNotMatch(markup, /aria-label="Storage quota usage"/u);
  assert.doesNotMatch(markup, /no quota configured/u);
  assert.doesNotMatch(markup, /aria-hidden="true" class="mb-1 h-1 w-full rounded-full bg-muted-foreground\/40"/u);
  assert.doesNotMatch(sidebarMarkup, /Local demo|Loopback only · No sign-in in this phase/u);
  assert.match(sidebarMarkup, /mt-auto/u);
  assert.match(markup, /<div class="mb-4 flex flex-wrap items-center gap-2 lg:hidden"><section aria-label="Storage usage"[^>]*class="min-w-\[9rem\] flex-1 rounded-lg border border-border bg-background px-3 py-2"/u);
  assert.equal(markup.match(/<section aria-label="Storage usage"/gu)?.length, 2);
  assert.match(markup, /Loading storage…/u);
  assert.doesNotMatch(markup, /<div aria-label="Storage usage" class="mr-2/u);
  assert.match(markup, /aria-label="Drive view"/u);
  assert.match(markup, /aria-label="List view" aria-pressed="true"/u);
  assert.match(markup, /aria-label="Grid view" aria-pressed="false"/u);
  assert.match(markup, /New<\/button>/u);
  assert.match(markup, /aria-label="Search all Drive"/u);
  assert.match(markup, /Search all Drive/u);
  assert.match(markup, /Search all files and folders/u);
  assert.match(markup, /Upload files/u);
  assert.doesNotMatch(markup, /aria-label="Folder path"/u);
  assert.match(markup, /<details aria-label="Filters and sorting"[^>]*class="shrink-0 rounded-lg border border-border\/80 bg-background px-3 py-1 shadow-sm open:order-3 open:w-full sm:hidden"/u);
  assert.match(markup, /<div aria-label="Filters and sorting" class="mb-5 hidden w-full items-center justify-between gap-5 rounded-xl border border-border\/80 bg-background px-5 py-4 shadow-sm sm:flex">[\s\S]*?Filter and sort[\s\S]*?Narrow items by type or choose their order\.[\s\S]*?<div aria-label="Drive filters" class="grid shrink-0 grid-cols-\[11rem_12rem\] items-end gap-3">/u);
  assert.match(markup, /aria-label="Filter by file type"/u);
  assert.match(markup, /aria-label="Sort Drive entries"/u);
  assert.doesNotMatch(markup, /aria-label="Modified after"|aria-label="Modified before"|aria-label="Minimum file size in bytes"|aria-label="Maximum file size in bytes"/u);
  assert.doesNotMatch(markup, /Reset Filters/u);
  assert.match(markup, /Loading your Drive/u);
  assert.doesNotMatch(markup, /Shared with me|Starred/u);
});
